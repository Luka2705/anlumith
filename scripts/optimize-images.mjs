import sharp from 'sharp';
import { mkdir, stat, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputDirectory = resolve(root, 'public/echo');
const widths = [360, 600, 900];
const imageNames = ['feed-original', 'map-americas', 'map-asia'];
const manifest = {};
const measurements = [];

await mkdir(outputDirectory, { recursive: true });

// Keep the supplied PNGs intact: they remain available behind the original-image links.
for (const name of imageNames) {
  const source = resolve(outputDirectory, `${name}.png`);
  const metadata = await sharp(source).metadata();
  const originalBytes = (await stat(source)).size;
  for (const width of widths) {
    const filename = `${name}-${width}.webp`;
    await sharp(source)
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 82, effort: 6 })
      .toFile(resolve(outputDirectory, filename));
    const bytes = (await stat(resolve(outputDirectory, filename))).size;
    measurements.push({ image: name, width, originalBytes, bytes, reduction: `${((1 - bytes / originalBytes) * 100).toFixed(1)}%` });
  }
  manifest[name] = {
    src: `/echo/${name}-600.webp`,
    srcSet: widths.map(width => `/echo/${name}-${width}.webp ${width}w`).join(', '),
    original: `/echo/${name}.png`,
    width: metadata.width,
    height: metadata.height,
  };
}

// Small genuine brand assets for browser and iOS home-screen icons.
const logoSource = resolve(root, 'public/echo-icon.png');
await sharp(logoSource).resize(64, 64).png().toFile(resolve(root, 'public/echo-icon-64.png'));
await sharp(logoSource).resize(180, 180).png().toFile(resolve(root, 'public/apple-touch-icon.png'));

// Render the share card from text and the existing brand image; no invented metrics.
const card = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
  <rect width="1200" height="630" fill="#151515"/>
  <path d="M72 72H1128" stroke="#41413A"/>
  <text x="72" y="121" font-family="Arial,Helvetica,sans-serif" font-size="17" letter-spacing="3" fill="#B6B7AC">SOCIAL MUSIC DISCOVERY</text>
  <text x="66" y="278" font-family="Arial,Helvetica,sans-serif" font-weight="700" font-size="102" letter-spacing="-5" fill="#F4F1EA">Echo Music<tspan fill="#FF9638">.</tspan></text>
  <text x="72" y="356" font-family="Arial,Helvetica,sans-serif" font-size="35" letter-spacing="-0.5" fill="#D8D7CB">Discover music.</text>
  <text x="72" y="405" font-family="Arial,Helvetica,sans-serif" font-size="35" letter-spacing="-0.5" fill="#D8D7CB">Share your world.</text>
  <path d="M72 510H1128" stroke="#41413A"/>
  <text x="72" y="557" font-family="Arial,Helvetica,sans-serif" font-size="16" letter-spacing="2" fill="#B6B7AC">PEOPLE. MUSIC. PLACES.</text>
  <text x="1128" y="557" text-anchor="end" font-family="Arial,Helvetica,sans-serif" font-size="16" letter-spacing="1.5" fill="#FFAB61">INVESTOR OVERVIEW</text>
</svg>`);
const logo = await sharp(logoSource).resize(330, 330).png().toBuffer();
await sharp(card)
  .composite([{ input: logo, left: 807, top: 148 }])
  .jpeg({ quality: 90, mozjpeg: true })
  .toFile(resolve(outputDirectory, 'echo-music-investors.jpg'));

const manifestSource = `// Generated by scripts/optimize-images.mjs. Original PNGs remain untouched.\nexport const screenshotImages = Object.freeze(${JSON.stringify(manifest, null, 2)});\n\nexport const socialImage = Object.freeze({\n  src: '/echo/echo-music-investors.jpg',\n  width: 1200,\n  height: 630,\n  type: 'image/jpeg',\n  alt: 'Echo Music. Social music discovery. Discover music. Share your world.',\n});\n`;
await writeFile(resolve(root, 'src/investor/image-assets.js'), manifestSource);
console.table(measurements);
console.log('Created responsive screenshots, browser icons, and 1200×630 share image.');
